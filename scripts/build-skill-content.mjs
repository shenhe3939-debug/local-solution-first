#!/usr/bin/env node
/**
 * Generate lib/skill-content.mjs from SKILL.md.
 *
 * The plugin registers the skill from memory (see lib/index.mjs), so the body has
 * to be a static module: registering a skill must not touch the disk at apply
 * time, and the bundled copy has to stay byte-identical to the SKILL.md shipped
 * in this repository. Run `node scripts/build-skill-content.mjs` after any
 * SKILL.md change; the generated header records the SKILL.md digest it came from.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(join(root, "SKILL.md"), "utf8");

const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(source);
if (match === null) throw new Error("SKILL.md: YAML frontmatter is missing");
const frontmatter = match[1];
// The filesystem provider loads a directory bundle's content as the body after
// the frontmatter, trimmed (`content: parsed.body.trim()`); match it exactly so a
// skill registered by this plugin and one discovered from a copied SKILL.md are
// byte-identical.
const body = source.slice(match[0].length).trim();

/** Read one scalar frontmatter field, or fail loudly when it is absent. */
function field(fieldName) {
  const found = new RegExp(`^${fieldName}:\\s*(.+)$`, "m").exec(frontmatter);
  if (found === null) throw new Error(`SKILL.md: frontmatter field "${fieldName}" is missing`);
  return found[1].trim();
}

const name = field("name");
const description = field("description");
const whenToUse = field("whenToUse");
if (name !== "local-solution-first") throw new Error(`SKILL.md: unexpected skill name "${name}"`);

const digest = createHash("sha256").update(source).digest("hex").toUpperCase();
const generated = [
  "// Generated by scripts/build-skill-content.mjs — do not edit by hand.",
  `// Source: SKILL.md (SHA-256 ${digest})`,
  `export const SKILL_NAME = ${JSON.stringify(name)};`,
  `export const SKILL_DESCRIPTION = ${JSON.stringify(description)};`,
  `export const SKILL_WHEN_TO_USE = ${JSON.stringify(whenToUse)};`,
  `export const SKILL_BODY = ${JSON.stringify(body)};`,
  ""
].join("\n");

writeFileSync(join(root, "lib", "skill-content.mjs"), generated);
console.log(
  `lib/skill-content.mjs: name=${name} sha256=${digest} description=${description.length} chars whenToUse=${whenToUse.length} chars body=${Buffer.byteLength(body, "utf8")} bytes`
);
